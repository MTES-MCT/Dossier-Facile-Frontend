    <h2 class="fr-h6">1. Bien définir ses critères de recherche🧐📝</h2>
    <p class="fr-mb-0">
      Avant de vous lancer dans la recherche d'un appartement, il est important de définir vos
      critères de recherche. Quel est le type de logement que vous préférez (studio, T2, T3, etc.) ?
    </p>
    <p>
      Quelle est la surface dont vous avez besoin ? Combien de pièces souhaitez-vous ? Quel est le
      quartier qui vous convient le mieux ? Quel est le montant du loyer que vous pouvez payer ?
      Êtes-vous prêt à partager un appartement ou préférez-vous vivre seul ? Quels sont les services
      ou les équipements que vous recherchez (meublés ou non, parking, cave, ascenseur, balcon,
      etc.) ?
    </p>
    <p>
      Réfléchissez également aux commodités et aux services auxquels vous attachez de l’importance,
      tels que la proximité des transports en commun, des écoles, des magasins ou des parcs.
    </p>
    <p>Ces questions vous permettront de cibler votre recherche et de gagner du temps.</p>

    <h2 class="fr-h6">2. Constituer son dossier de location en béton📁</h2>
    <p class="fr-mb-0">
      Si vous avez trouvé un appartement qui vous plaît et qui correspond à vos critères, il ne vous
      reste plus qu'à constituer votre dossier de location.
    </p>
    <p>
      Un dossier clair, complet et cohérent est la clé d'une location réussie. Il valorise votre
      profil et rassure le propriétaire.
    </p>
    <p>
      En effet, la compétition est rude : vous êtes souvent nombreux à visiter les mêmes
      appartements et à soumettre vos dossiers aux mêmes propriétaires. Mettez toutes les chances de
      votre côté et distinguez vous avec un dossier bien à jour. Des documents conformes, récents,
      et de bonne qualité feront la différence auprès de votre futur propriétaire.
    </p>
    <p class="fr-mb-0">
      <a href="https://www.dossierfacile.logement.gouv.fr/">DossierFacile</a> vous aide à constituer
