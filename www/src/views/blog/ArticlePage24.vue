    </p>
    <p>
      Conçu pour répondre aux attentes des bailleurs et protéger les locataires, la sécurité est
      l’un des points clés du service : afin de protéger vos fichiers personnels et vos données
      sensibles, DossierFacile vérifie chaque dossier puis y appose un filigrane pour prévenir les
      risques de fraude, falsification ou usurpation d’identité.
